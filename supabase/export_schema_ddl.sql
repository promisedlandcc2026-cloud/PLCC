select x.grp, x.sql from xmltable('/table/row' passing query_to_xml($q$
with
tbl as (
  select c.oid, c.relname, c.relrowsecurity, c.relforcerowsecurity
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind in ('r','p')
    and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'e')
),
cols as (
  select t.oid, t.relname, a.attnum, a.attname, a.attnotnull, a.attidentity, a.attgenerated,
         format_type(a.atttypid, a.atttypmod) typ, pg_get_expr(ad.adbin, ad.adrelid) defexpr
  from tbl t join pg_attribute a on a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped
  left join pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
),
fns as (
  select p.oid from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind in ('f','p')
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
),
stmts as (
  select 10 grp, s.sequencename::text k, 0 sub,
    format('create sequence if not exists public.%I', s.sequencename) sql
  from pg_sequences s where s.schemaname = 'public'
  union all
  select 20, t.relname, 0,
    format('create table if not exists public.%I (%s)', t.relname,
      coalesce((select string_agg(
        format('%I %s', c.attname, c.typ)
        || case when c.attidentity = 'a' then ' generated always as identity'
                when c.attidentity = 'd' then ' generated by default as identity' else '' end
        || case when c.attgenerated = 's' then format(' generated always as (%s) stored', c.defexpr) else '' end
        || case when c.attnotnull then ' not null' else '' end, ', ' order by c.attnum)
       from cols c where c.oid = t.oid), ''))
  from tbl t
  union all
  select 30, p.oid::text, 0, 'set check_function_bodies = off' || chr(59) || ' ' || pg_get_functiondef(p.oid)
  from fns f join pg_proc p on p.oid = f.oid
  union all
  select 40, c.relname, c.attnum,
    format('alter table public.%I alter column %I set default %s', c.relname, c.attname, c.defexpr)
  from cols c where c.defexpr is not null and c.attgenerated = '' and c.attidentity = ''
  union all
  select case when con.contype = 'f' then 60 else 50 end, rel.relname, con.oid::int,
    format('alter table public.%I add constraint %I %s', rel.relname, con.conname, pg_get_constraintdef(con.oid))
  from pg_constraint con join tbl rel on rel.oid = con.conrelid
  where con.contype in ('p','u','c','x','f')
  union all
  select 70, i.tablename, 0, i.indexdef
  from pg_indexes i
  where i.schemaname = 'public'
    and i.tablename in (select relname from tbl)
    and not exists (select 1 from pg_constraint con join pg_class ic on ic.oid = con.conindid
                    where ic.relname = i.indexname and con.contype in ('p','u','x'))
  union all
  select 80, v.viewname, 0,
    format('create or replace view public.%I%s as %s', v.viewname,
      coalesce((select ' with (' || array_to_string(c.reloptions, ', ') || ')'
                from pg_class c join pg_namespace n on n.oid = c.relnamespace
                where n.nspname = 'public' and c.relname = v.viewname and c.reloptions is not null), ''),
      v.definition)
  from pg_views v where v.schemaname = 'public'
  union all
  select 90, c.relname, 0, pg_get_triggerdef(tg.oid)
  from pg_trigger tg join tbl c on c.oid = tg.tgrelid where not tg.tgisinternal
  union all
  select 100, t.relname, 0, format('alter table public.%I enable row level security', t.relname)
  from tbl t where t.relrowsecurity
  union all
  select 100, t.relname, 1, format('alter table public.%I force row level security', t.relname)
  from tbl t where t.relforcerowsecurity
  union all
  select 110, p.tablename || '.' || p.policyname, 0,
    format('create policy %I on public.%I as %s for %s to %s%s%s', p.policyname, p.tablename,
      p.permissive, p.cmd, array_to_string(p.roles, ', '),
      case when p.qual is not null then ' using (' || p.qual || ')' else '' end,
      case when p.with_check is not null then ' with check (' || p.with_check || ')' else '' end)
  from pg_policies p where p.schemaname = 'public'
  union all
  select 120, pt.tablename, 0, format('alter publication supabase_realtime add table public.%I', pt.tablename)
  from pg_publication_tables pt where pt.pubname = 'supabase_realtime' and pt.schemaname = 'public'
)
select grp, string_agg(sql || chr(59), E'\n' order by k, sub) as sql from stmts group by grp order by grp
$q$, false, false, '') columns grp int path 'grp', sql text path 'sql') as x order by x.grp